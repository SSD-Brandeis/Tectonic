#!/usr/bin/env python3
"""Derived YCSB workload-generation plot with modified db_bench.

This script intentionally does not overwrite experiment_plots/ycsb_workloads_comparison.pdf.
It reads the existing Tectonic/YCSB/KVBench logs from logs_fig3 and adds
DBBench_* logs generated by modified RocksDB db_bench --benchmarks=ycsbtrace.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.patches as mpatches
import matplotlib.pyplot as plt
import matplotlib.ticker as mticker
import numpy as np

sys.path.append(str(Path(__file__).resolve().parent))
import plot_style  # noqa: E402


ROOT_DIR = Path(__file__).resolve().parents[1]
EXISTING_LOG_DIR = ROOT_DIR / "data" / "overall_benchmarks" / "logs_fig3"
DB_BENCH_LOG_DIR = ROOT_DIR / "data" / "overall_benchmarks" / "db_bench_ycsb_workloads"
OUT_BASE = ROOT_DIR / "experiment_plots" / "ycsb_workloads_comparison_with_db_bench"
WORKLOADS = ["A", "B", "C", "D", "E", "F"]
TOTAL_OPS = 2_000_000

TOOLS = ["Tectonic", "YCSB", "KVBench", "DBBench"]
LABELS = {
    "Tectonic": "Tectonic+",
    "YCSB": "YCSB",
    "KVBench": "KVBench",
    "DBBench": r"db\_bench",
}
BAR_STYLES = {
    "Tectonic": {"facecolor": "tab:red", "edgecolor": "tab:red", "hatch": ""},
    "YCSB": {"facecolor": "white", "edgecolor": "grey", "hatch": "///"},
    "KVBench": {"facecolor": "white", "edgecolor": "tab:blue", "hatch": "\\\\"},
    "DBBench": {"facecolor": "white", "edgecolor": "tab:green", "hatch": "xx"},
}


def parse_elapsed_wall_clock(time_str: str) -> float:
    parts = time_str.strip().split(":")
    if len(parts) == 2:
        return float(parts[0]) * 60 + float(parts[1])
    if len(parts) == 3:
        return float(parts[0]) * 3600 + float(parts[1]) * 60 + float(parts[2])
    return 0.0


def parse_time_v_log(path: Path) -> tuple[float, float]:
    elapsed = 0.0
    max_rss_mib = 0.0
    with path.open(errors="replace") as f:
        for line in f:
            if "Elapsed (wall clock) time" in line:
                elapsed += parse_elapsed_wall_clock(line.split("): ")[-1].strip())
            elif "Maximum resident set size (kbytes):" in line:
                max_rss_mib = max(max_rss_mib, float(line.split(":")[-1].strip()) / 1024.0)
    return max(elapsed, 0.001), max_rss_mib


def log_path(tool: str, workload: str) -> Path:
    if tool == "DBBench":
        return DB_BENCH_LOG_DIR / f"DBBench_{workload}.log"
    return EXISTING_LOG_DIR / f"{tool}_{workload}.log"


def collect_metrics() -> tuple[dict[str, list[float]], dict[str, list[float]], dict[str, list[float]]]:
    times = {tool: [] for tool in TOOLS}
    throughputs = {tool: [] for tool in TOOLS}
    memory = {tool: [] for tool in TOOLS}
    for workload in WORKLOADS:
        for tool in TOOLS:
            if tool == "KVBench" and workload == "F":
                times[tool].append(0.0)
                throughputs[tool].append(0.0)
                memory[tool].append(0.0)
                continue
            path = log_path(tool, workload)
            if not path.exists():
                times[tool].append(0.0)
                throughputs[tool].append(0.0)
                memory[tool].append(0.0)
                continue
            elapsed, rss = parse_time_v_log(path)
            times[tool].append(elapsed)
            throughputs[tool].append(TOTAL_OPS / elapsed)
            memory[tool].append(rss)
    return times, throughputs, memory


def apply_axes(ax, title: str, ylabel: str) -> None:
    plot_style.apply_plot_style(ax, title=title, ylabel=ylabel)
    for label in ax.get_xticklabels() + ax.get_yticklabels():
        label.set_fontweight("normal")


def save_legend_pdf() -> None:
    handles = [
        mpatches.Patch(
            facecolor=BAR_STYLES[tool]["facecolor"],
            edgecolor=BAR_STYLES[tool]["edgecolor"],
            hatch=BAR_STYLES[tool]["hatch"],
            label=LABELS[tool],
            linewidth=1.0,
        )
        for tool in TOOLS
    ]
    fig = plt.figure(figsize=(8.5, 0.75))
    fig.legend(handles=handles, loc="center", ncol=len(handles), frameon=False)
    fig.savefig(f"{OUT_BASE}_legend.pdf", bbox_inches="tight", pad_inches=0.05)
    plt.close(fig)


def plot() -> None:
    times, throughputs, memory = collect_metrics()
    x = np.arange(len(WORKLOADS))
    width = 0.18
    offsets = [-1.5 * width, -0.5 * width, 0.5 * width, 1.5 * width]
    fig, axs = plt.subplots(1, 3, figsize=(15, 4))

    for offset, tool in zip(offsets, TOOLS):
        axs[0].bar(x + offset, times[tool], width, label=LABELS[tool], **BAR_STYLES[tool])
    axs[0].set_xticks(x)
    axs[0].set_xticklabels(WORKLOADS)
    axs[0].set_yscale("log")
    axs[0].yaxis.set_major_locator(mticker.LogLocator(base=10))
    axs[0].yaxis.set_major_formatter(mticker.LogFormatterMathtext(base=10))
    axs[0].yaxis.set_minor_locator(mticker.NullLocator())
    apply_axes(axs[0], "(a) workload generation time", "workload generation time (s)")

    for offset, tool in zip(offsets, TOOLS):
        axs[1].bar(x + offset, [value / 1e5 for value in throughputs[tool]], width, label=LABELS[tool], **BAR_STYLES[tool])
    axs[1].set_xticks(x)
    axs[1].set_xticklabels(WORKLOADS)
    axs[1].text(0.01, 0.99, r"$\times10^5$", transform=axs[1].transAxes, va="top", ha="left", fontsize=10)
    apply_axes(axs[1], "(b) generation throughput", "throughput (ops/s)")

    for offset, tool in zip(offsets, TOOLS):
        axs[2].bar(x + offset, memory[tool], width, label=LABELS[tool], **BAR_STYLES[tool])
    axs[2].set_xticks(x)
    axs[2].set_xticklabels(WORKLOADS)
    apply_axes(axs[2], "(c) peak memory footprint", "memory footprint (MB)")

    OUT_BASE.parent.mkdir(parents=True, exist_ok=True)
    save_legend_pdf()
    fig.tight_layout()
    fig.savefig(f"{OUT_BASE}.pdf", bbox_inches="tight")
    plt.close(fig)
    print(f"saved: {OUT_BASE}.pdf")
    print(f"saved: {OUT_BASE}_legend.pdf")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Plot YCSB workload generation comparison with modified db_bench.",
    )
    parser.parse_args()
    plot()


if __name__ == "__main__":
    main()
